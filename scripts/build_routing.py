#!/usr/bin/env python3
"""Generate the CONTEXT.md routing table and the bundle index files from
knowledge/ frontmatter.

Source of truth: the `domains`, `depth`, `model`, `title`, and `description`
fields of each concept file under knowledge/<bundle>/. Files in
knowledge/conventions/ are not routed (CLAUDE.md links them directly), and
index.md files are regenerated rather than read.

Usage:
    python scripts/build_routing.py

Run it after editing any concept file's frontmatter. check_routing.py fails
when CONTEXT.md is out of date with what this script would write.
"""

from __future__ import annotations

import re
import sys

from claude_home import CONTEXT_FILE, KNOWLEDGE_DIR, as_list, as_str, parse_frontmatter, utf8_stdout

MARKER_START = "<!-- GENERATED by build_routing.py: do not hand-edit -->"
MARKER_END = "<!-- END GENERATED -->"
RICH_PREFIX = "(rich) "

# The routing taxonomy. A concept file's `domains` must use these keys
# (frontmatter_audit.py enforces it). Add a key here to add a section.
DOMAIN_LABELS: dict[str, str] = {
    "ui": "UI / Visual Design",
    "ux": "UX / Experience Design",
    "apple": "Apple Platforms",
    "android": "Android",
    "mobile": "Mobile (cross-platform)",
    "windows": "Windows",
    "security": "Security",
    "code-review": "Code Review",
    "code-simplification": "Code Simplification / DRY",
    "engineering": "Engineering",
    "orchestration": "Orchestration and Multi-Session Work",
    "iot": "IoT / Hardware",
    "ai-ml": "AI / Machine Learning",
    "marketing": "Marketing and Growth",
    "seo": "SEO",
    "writing": "Content Writing",
    "research": "Research and Evidence Discipline",
    "technical-documentation": "Technical Documentation",
    "standards": "Documentation Standards",
    "process": "Process and Quality",
    "legal": "Legal and Compliance",
    "llm": "LLM Evaluation",
    "data": "Data Engineering / Science",
    "cloud": "Cloud and DevOps",
    "business": "Business and Strategy",
    "supply-chain": "Supply Chain and Operations",
}

# Section order in CONTEXT.md; domains not listed here follow alphabetically.
DOMAIN_ORDER = list(DOMAIN_LABELS)

SKIP_NAMES = {"index.md"}
SKIP_DIRS = {"conventions"}

BUNDLES = ("skills", "agents", "marketplaces")
BUNDLE_INTROS: dict[str, str] = {
    "skills": (
        "# Skills Domain Index\n\nSkills live at `~/.claude/skills/<name>/SKILL.md`. Invoke with `/<name>`.\n\n"
    ),
    "agents": "# Agents Bundle Index\n\n",
    "marketplaces": "# Marketplaces and Plugins Index\n\n",
}


def collect_entries() -> list[dict]:
    entries: list[dict] = []
    if not KNOWLEDGE_DIR.is_dir():
        return entries
    for subdir in sorted(KNOWLEDGE_DIR.iterdir()):
        if not subdir.is_dir() or subdir.name in SKIP_DIRS:
            continue
        for f in sorted(subdir.glob("*.md")):
            if f.name in SKIP_NAMES:
                continue
            fm = parse_frontmatter(f)
            domains = as_list(fm.get("domains"))
            if not domains:
                continue
            entries.append(
                {
                    "path": f"knowledge/{subdir.name}/{f.name}",
                    "bundle": subdir.name,
                    "name": f.stem,
                    "type": as_str(fm.get("type")),
                    "title": as_str(fm.get("title")) or f.stem,
                    "desc": as_str(fm.get("description")),
                    "domains": domains,
                    "depth": as_str(fm.get("depth")) or "single",
                    "model": as_str(fm.get("model")),
                }
            )
    return entries


def build_routing_block(entries: list[dict]) -> str:
    domain_map: dict[str, list[dict]] = {}
    for entry in entries:
        for domain in entry["domains"]:
            domain_map.setdefault(domain, []).append(entry)

    ordered = [d for d in DOMAIN_ORDER if d in domain_map]
    ordered += sorted(d for d in domain_map if d not in ordered)

    lines: list[str] = [
        MARKER_START,
        "",
        "## Routing Table",
        "",
        "Generated from `knowledge/` frontmatter. Open the linked concept file for the full",
        f"skill and agent lists. `{RICH_PREFIX.strip()}` marks a concept with sub-skills or several",
        "sections: load the concept file, not just this row.",
        "Run `python scripts/build_routing.py` after editing any frontmatter `domains` field.",
        "",
    ]

    for domain in ordered:
        lines += [
            f"### {domain}: {DOMAIN_LABELS.get(domain, domain)}",
            "",
            "| Concept | Type | Model | Description |",
            "| ------- | ---- | ----- | ----------- |",
        ]
        seen: set[str] = set()
        for entry in sorted(domain_map[domain], key=lambda e: (e["bundle"], e["title"])):
            if entry["path"] in seen:
                continue
            seen.add(entry["path"])
            prefix = RICH_PREFIX if entry["depth"] == "rich" else ""
            link = f"[{prefix}{entry['title']}]({entry['path']})"
            lines.append(f"| {link} | {entry['type']} | {entry['model']} | {entry['desc']} |")
        lines.append("")

    lines.append(MARKER_END)
    return "\n".join(lines)


def splice(text: str, block: str) -> str:
    """Replace the generated block in text, or append it when absent."""
    if MARKER_START in text and MARKER_END in text:
        start = text.index(MARKER_START)
        end = text.index(MARKER_END) + len(MARKER_END)
        return text[:start] + block + text[end:]
    return text.rstrip() + "\n\n" + block + "\n"


def update_context(block: str) -> None:
    text = CONTEXT_FILE.read_text(encoding="utf-8") if CONTEXT_FILE.exists() else "# Task Routing\n"
    new_text = splice(text, block)
    if new_text != text:
        CONTEXT_FILE.write_text(new_text, encoding="utf-8", newline="\n")
        print(f"  updated: {CONTEXT_FILE}")
    else:
        print(f"  current: {CONTEXT_FILE}")


def bundle_index(bundle: str, entries: list[dict], existing: str) -> str | None:
    """The regenerated index.md text for a bundle, or None without frontmatter."""
    match = re.match(r"^(---\r?\n.*?\r?\n---\r?\n)", existing, re.DOTALL)
    if not match:
        return None
    rows = ["| File | Description |", "| ---- | ----------- |"]
    for entry in sorted(entries, key=lambda e: e["title"]):
        prefix = RICH_PREFIX if entry["depth"] == "rich" else ""
        rows.append(f"| [{prefix}{entry['title']}]({entry['name']}.md) | {entry['desc']} |")
    intro = BUNDLE_INTROS.get(bundle, f"# {bundle.title()} Index\n\n")
    return match.group(1) + "\n" + intro + "\n".join(rows) + "\n"


def regenerate_bundle_indexes(entries: list[dict]) -> None:
    for bundle in BUNDLES:
        index_path = KNOWLEDGE_DIR / bundle / "index.md"
        if not index_path.exists():
            continue
        existing = index_path.read_text(encoding="utf-8")
        new_content = bundle_index(bundle, [e for e in entries if e["bundle"] == bundle], existing)
        if new_content is None:
            print(f"  WARN: no frontmatter in {index_path}", file=sys.stderr)
        elif new_content != existing:
            index_path.write_text(new_content, encoding="utf-8", newline="\n")
            print(f"  updated: {index_path}")


def main() -> None:
    utf8_stdout()
    entries = collect_entries()
    if not entries:
        print("ERROR: no concept files with a 'domains' field under knowledge/", file=sys.stderr)
        sys.exit(1)
    print(f"Found {len(entries)} concept files with domains")
    update_context(build_routing_block(entries))
    regenerate_bundle_indexes(entries)
    print("Done.")


if __name__ == "__main__":
    main()
